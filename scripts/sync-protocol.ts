// Copies src/protocol.ts (the wire format) into felt-web.
// Usage: bun run sync-protocol [target]   (default: ../felt-web/src/net/protocol.ts)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const target = process.argv[2] ?? "../felt-web/src/net/protocol.ts";
const source = readFileSync("src/protocol.ts", "utf8");

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by felt-server (bun run sync-protocol). Do not edit here: change src/protocol.ts in felt-server.\n${source}`,
);
console.log(`protocol.ts -> ${target}`);
